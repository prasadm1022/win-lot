// Golden fixture of win-lot-jackpot-v2 (docs/MODEL-V2.md section 6): test/fixtures/model-v2-golden.json freezes a
// data snapshot (Dhana Nidhanaya, Govisetha and Mega Power in full, the last 700 draws of Ada Kotipathi and Kapruka,
// jackpots.json and prizes) and the full v2 payloads; recomputing them must give a deep-equal result (like
// model-parity.json for v1). Regenerate with `npm run golden:model` only on a deliberate model change.
//
// On the 2026-10-27 snapshot, the NLB lotteries (whole archive) must also show the spec's measured numbers
// (sections 1, 2.4, 2.7, 2.11, 2.12, 2.14, 2.15, 3.3, 5.5 and 7.3; acceptance 8.1 items 3, 5, 6), within the spec's
// printed precision.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { beforeAll, describe, expect, it } from "vitest";
import type { Jackpot } from "../lib/jackpots";
import type { Lottery } from "../lib/lotteries";
import { predict } from "../lib/model";
import { MODEL_VERSION_V2, V2_CONSTANTS, predictAllV2 } from "../lib/model-v2";
import type { Draw } from "../lib/parsers";
import type { Prediction } from "../lib/types";

interface GoldenFixture {
  modelVersion: string;
  constants: unknown;
  snapshot: {
    asOf: string;
    lotteries: { lottery: Lottery; generatedAt: string; draws: Draw[] }[];
    jackpots: Jackpot[];
    prizes: Record<string, unknown[]>;
  };
  expected: Record<string, Prediction>;
}

const FIXTURE: GoldenFixture = JSON.parse(readFileSync(join(__dirname, "fixtures", "model-v2-golden.json"), "utf8"));
let actual: Record<string, Prediction> = {};

beforeAll(() => {
  const { lotteries, jackpots } = FIXTURE.snapshot;
  actual = predictAllV2(
    lotteries.map(({ lottery, draws, generatedAt }) => ({ lottery, draws, jackpots, generatedAt, v1: predict(lottery, draws, generatedAt) })),
  );
}, 120_000);

describe("golden fixture", () => {
  it("was generated by this model version with these constants", () => {
    expect(FIXTURE.modelVersion).toBe(MODEL_VERSION_V2);
    expect(FIXTURE.constants).toEqual(JSON.parse(JSON.stringify(V2_CONSTANTS)));
  });

  it("freezes the snapshot the spec describes", () => {
    const { lotteries, jackpots, prizes } = FIXTURE.snapshot;
    expect(lotteries.map((l) => [l.lottery.id, l.draws.length])).toEqual([
      ["dhana-nidhanaya", 208],
      ["mega-power", 208],
      ["govisetha", 208],
      ["ada-kotipathi", 700],
      ["kapruka", 700],
    ]);
    expect(jackpots.length).toBeGreaterThan(0);
    expect(Object.keys(prizes).sort()).toEqual(lotteries.map((l) => l.lottery.id).sort());
    // The out-of-use balls of Ada Kotipathi and Kapruka are inside the snapshot.
    expect(FIXTURE.expected["ada-kotipathi"].liveBalls!.excluded).toEqual([77, 78, 79, 80]);
    expect(FIXTURE.expected["kapruka"].liveBalls!.excluded).toEqual([76, 77, 78, 79, 80]);
  });

  for (const id of ["dhana-nidhanaya", "mega-power", "govisetha", "ada-kotipathi", "kapruka"]) {
    it(`${id}: the full v2 payload deep-equals the fixture`, () => {
      expect(actual[id]).toEqual(FIXTURE.expected[id]);
    });
  }

  it("no other lottery is in the output", () => {
    expect(Object.keys(actual)).toEqual(Object.keys(FIXTURE.expected));
  });
});

/** |actual - spec| within half a unit of the spec's last printed decimal (plus float slack). */
function near(actual: number, spec: number, decimals: number) {
  expect(Math.abs(actual - spec), `${actual} vs spec ${spec}`).toBeLessThanOrEqual(0.5 * 10 ** -decimals + 1e-9);
}

