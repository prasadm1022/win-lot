"""Backfill the full available history of all seven lotteries.

Usage (from repo root):
    scraper/.venv/Scripts/python scraper/backfill.py            # scrape (cached) + db + SQL
    scraper/.venv/Scripts/python scraper/backfill.py --no-cache # ignore today's cache
    scraper/.venv/Scripts/python scraper/backfill.py --only super-ball

Outputs:
    data/lottery.sqlite         local SQLite copy (same schema as D1)
    migrations/0001_schema.sql  D1 schema
    seed/*.sql                  chunked INSERT OR IGNORE files for `wrangler d1 execute --file`
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import sqlite3
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from fetch import Fetcher  # noqa: E402
from lotteries import BY_ID, LOTTERIES  # noqa: E402
from parsers import normalize, parse_dlb_latest, parse_dlb_page, parse_nlb  # noqa: E402
import model  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DB_PATH = ROOT / "data" / "lottery.sqlite"
SCHEMA_PATH = ROOT / "migrations" / "0001_schema.sql"
SEED_DIR = ROOT / "seed"
DLB_PAGINATION = "https://www.dlb.lk/result/pagination_re"
MAX_DLB_PAGES = 1000          # safety cap (~12 draws/page)
ROWS_PER_STATEMENT = 40       # keeps each INSERT well under D1's statement size limit
STATEMENTS_PER_FILE = 25      # 1000 rows per seed file

SCHEMA = """-- win-lot D1 schema (generated by scraper/backfill.py; keep in sync with docs/ARCHITECTURE.md)
CREATE TABLE IF NOT EXISTS lotteries (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  board TEXT NOT NULL,
  source_url TEXT NOT NULL,
  letter_kind TEXT NOT NULL DEFAULT 'none',
  main_count INTEGER NOT NULL,
  main_min INTEGER NOT NULL,
  main_max INTEGER NOT NULL,
  has_bonus INTEGER NOT NULL DEFAULT 0,
  bonus_label TEXT,
  bonus_min INTEGER,
  bonus_max INTEGER
);
CREATE TABLE IF NOT EXISTS draws (
  lottery_id TEXT NOT NULL,
  draw_no INTEGER NOT NULL,
  draw_date TEXT NOT NULL,
  letter TEXT,
  numbers TEXT NOT NULL,
  bonus TEXT,
  fetched_at TEXT NOT NULL,
  PRIMARY KEY (lottery_id, draw_no)
);
CREATE INDEX IF NOT EXISTS idx_draws_lottery_date ON draws (lottery_id, draw_date);
CREATE TABLE IF NOT EXISTS predictions (
  lottery_id TEXT PRIMARY KEY,
  generated_at TEXT NOT NULL,
  payload TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS fetch_log (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  run_at TEXT NOT NULL,
  lottery_id TEXT,
  inserted INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL,
  message TEXT
);
CREATE INDEX IF NOT EXISTS idx_fetch_log_run_at ON fetch_log (run_at);
"""

LOTTERY_COLUMNS = ["id", "name", "board", "source_url", "letter_kind", "main_count", "main_min",
                   "main_max", "has_bonus", "bonus_label", "bonus_min", "bonus_max"]


def scrape_nlb(fetcher: Fetcher, lottery: dict) -> list[dict]:
    # NLB serves only the latest ~208 draws on the list page; there is no pagination and
    # per-draw pages (results/<slug>/<drawNo>) are empty for older draws (verified 2026-10-28).
    html = fetcher.get(lottery["source_url"])
    return parse_nlb(html)


def scrape_dlb(fetcher: Fetcher, lottery: dict) -> list[dict]:
    key = lottery["source_key"]
    latest = parse_dlb_latest(fetcher.get(lottery["source_url"]))
    rows = []
    result_id = ""
    if key in latest:
        rows.append(latest[key])
        result_id = latest[key]["result_id"]
    seen = {r["draw_no"] for r in rows}
    for page in range(MAX_DLB_PAGES):
        html = fetcher.post(DLB_PAGINATION, {"pageId": str(page), "resultID": result_id,
                                             "lotteryID": key, "lastsegment": key})
        page_rows = parse_dlb_page(html)
        new_rows = [r for r in page_rows if r["draw_no"] not in seen]
        if not new_rows:
            break
        rows.extend(new_rows)
        seen.update(r["draw_no"] for r in new_rows)
        if page % 20 == 0:
            print(f"  {lottery['id']}: page {page}, oldest {new_rows[-1]['draw_date']}", flush=True)
    return rows


def write_db(draws_by_lottery: dict[str, list[dict]], fetched_at: str) -> None:
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(DB_PATH)
    con.executescript(SCHEMA)
    con.executemany(
        f"INSERT OR REPLACE INTO lotteries ({','.join(LOTTERY_COLUMNS)}) VALUES ({','.join('?' * len(LOTTERY_COLUMNS))})",
        [[l[c] for c in LOTTERY_COLUMNS] for l in LOTTERIES])
    for lid, draws in draws_by_lottery.items():
        con.executemany(
            "INSERT OR REPLACE INTO draws (lottery_id, draw_no, draw_date, letter, numbers, bonus, fetched_at)"
            " VALUES (?,?,?,?,?,?,?)",
            [(lid, d["draw_no"], d["draw_date"], d["letter"], json.dumps(d["numbers"]),
              None if d["bonus"] is None else json.dumps(d["bonus"], separators=(",", ":")), fetched_at)
             for d in draws])
    con.commit()
    con.close()


def load_db() -> dict[str, list[dict]]:
    con = sqlite3.connect(DB_PATH)
    out: dict[str, list[dict]] = {}
    for lid, no, date, letter, numbers, bonus in con.execute(
            "SELECT lottery_id, draw_no, draw_date, letter, numbers, bonus FROM draws ORDER BY lottery_id, draw_no"):
        out.setdefault(lid, []).append(dict(draw_no=no, draw_date=date, letter=letter,
                                            numbers=json.loads(numbers),
                                            bonus=None if bonus is None else json.loads(bonus)))
    con.close()
    return out


def sql_literal(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def write_sql(fetched_at: str) -> list[Path]:
    SCHEMA_PATH.parent.mkdir(parents=True, exist_ok=True)
    SCHEMA_PATH.write_text(SCHEMA, encoding="utf-8")
    SEED_DIR.mkdir(parents=True, exist_ok=True)
    for old in SEED_DIR.glob("*.sql"):
        old.unlink()
    files = []
    lot_sql = "\n".join(
        f"INSERT OR REPLACE INTO lotteries ({','.join(LOTTERY_COLUMNS)}) VALUES "
        f"({','.join(sql_literal(l[c]) for c in LOTTERY_COLUMNS)});" for l in LOTTERIES)
    path = SEED_DIR / "0000_lotteries.sql"
    path.write_text(lot_sql + "\n", encoding="utf-8")
    files.append(path)

    draws = load_db()
    index = 1
    for lottery in LOTTERIES:
        rows = draws.get(lottery["id"], [])
        tuples = [
            "(" + ",".join([
                sql_literal(lottery["id"]), str(d["draw_no"]), sql_literal(d["draw_date"]),
                sql_literal(d["letter"]), sql_literal(json.dumps(d["numbers"], separators=(",", ":"))),
                "NULL" if d["bonus"] is None else sql_literal(json.dumps(d["bonus"], separators=(",", ":"))),
                sql_literal(fetched_at)]) + ")"
            for d in rows]
        statements = [
            "INSERT OR IGNORE INTO draws (lottery_id,draw_no,draw_date,letter,numbers,bonus,fetched_at) VALUES\n"
            + ",\n".join(tuples[i:i + ROWS_PER_STATEMENT]) + ";"
            for i in range(0, len(tuples), ROWS_PER_STATEMENT)]
        for part, start in enumerate(range(0, len(statements), STATEMENTS_PER_FILE)):
            path = SEED_DIR / f"{index:04d}_{lottery['id']}_{part + 1:02d}.sql"
            path.write_text("\n".join(statements[start:start + STATEMENTS_PER_FILE]) + "\n", encoding="utf-8")
            files.append(path)
            index += 1

    # Initial predictions so the site works before the first cron run.
    pred_lines = []
    for lottery in LOTTERIES:
        rows = draws.get(lottery["id"], [])
        if not rows:
            continue
        payload = model.predict(lottery, rows, generated_at=fetched_at)
        pred_lines.append(
            "INSERT OR REPLACE INTO predictions (lottery_id,generated_at,payload) VALUES ("
            f"{sql_literal(lottery['id'])},{sql_literal(fetched_at)},"
            f"{sql_literal(json.dumps(payload, separators=(',', ':')))});")
    path = SEED_DIR / "9000_predictions.sql"
    path.write_text("\n".join(pred_lines) + "\n", encoding="utf-8")
    files.append(path)
    return files


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-cache", action="store_true")
    ap.add_argument("--only", action="append", help="lottery id (repeatable)")
    ap.add_argument("--sql-only", action="store_true", help="skip scraping; regenerate SQL from data/lottery.sqlite")
    args = ap.parse_args()
    fetched_at = dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")

    if not args.sql_only:
        fetcher = Fetcher(use_cache=not args.no_cache)
        targets = [BY_ID[i] for i in args.only] if args.only else LOTTERIES
        result: dict[str, list[dict]] = {}
        for lottery in targets:
            started = dt.datetime.now()
            raw = scrape_nlb(fetcher, lottery) if lottery["board"] == "NLB" else scrape_dlb(fetcher, lottery)
            good = [n for n in (normalize(lottery, r) for r in raw) if n is not None]
            dedup = {d["draw_no"]: d for d in good}
            result[lottery["id"]] = sorted(dedup.values(), key=lambda d: d["draw_no"])
            rows = result[lottery["id"]]
            span = f"{rows[0]['draw_date']}..{rows[-1]['draw_date']}" if rows else "-"
            print(f"{lottery['id']}: raw={len(raw)} kept={len(rows)} skipped={len(raw) - len(good)} "
                  f"range={span} ({(dt.datetime.now() - started).seconds}s)", flush=True)
        write_db(result, fetched_at)
        print(f"network requests: {fetcher.network_requests}")

    files = write_sql(fetched_at)
    print(f"wrote {SCHEMA_PATH.relative_to(ROOT)} and {len(files)} seed files")


if __name__ == "__main__":
    main()
